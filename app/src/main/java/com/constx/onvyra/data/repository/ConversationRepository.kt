    suspend fun getConversationById(uuid: Uuid): Conversation? {
        if (temporaryChatRegistry.blocksStorage(uuid)) return null
        val entity = conversationDAO.getConversationById(uuid.toString())
        return if (entity != null) {
            val nodes = loadMessageNodes(entity.id)
            conversationEntityToConversation(entity, nodes)
        } else null
    }

    suspend fun existsConversationById(uuid: Uuid): Boolean {
        if (temporaryChatRegistry.blocksStorage(uuid)) return false
        return conversationDAO.existsById(uuid.toString())
    }

    /** Notification policy needs metadata only, never load private message bodies for a badge. */
    suspend fun isConversationLocked(uuid: Uuid): Boolean? {
        if (temporaryChatRegistry.blocksStorage(uuid)) return null
        return conversationDAO.getConversationById(uuid.toString())?.isLocked
    }

    suspend fun countConversations(): Int {
        return conversationDAO.countAll()
    }

    suspend fun countConversationsByAssistant(): Map<Uuid, Int> {
        return conversationDAO.countByAssistant().mapNotNull { row ->
            runCatching { Uuid.parse(row.assistantId) }.getOrNull()?.let { it to row.count }
        }.toMap()
    }

    suspend fun insertConversation(conversation: Conversation) {
        if (temporaryChatRegistry.blocksStorage(conversation.id)) return
        database.withTransaction {
            if (temporaryChatRegistry.blocksStorage(conversation.id)) return@withTransaction
            conversationDAO.insert(
                conversationToConversationEntity(conversation)
            )
            saveMessageNodes(conversation.id.toString(), conversation.messageNodes)
        }
        if (!temporaryChatRegistry.blocksStorage(conversation.id)) messageFtsManager.indexConversation(conversation)
    }

    suspend fun updateConversation(conversation: Conversation) {
        if (temporaryChatRegistry.blocksStorage(conversation.id)) return
        database.withTransaction {
            if (temporaryChatRegistry.blocksStorage(conversation.id)) return@withTransaction
            conversationDAO.update(
                conversationToConversationEntity(conversation)
            )
            // 删除旧的节点，插入新的节点
            messageNodeDAO.deleteByConversation(conversation.id.toString())
            saveMessageNodes(conversation.id.toString(), conversation.messageNodes)
        }
        if (!temporaryChatRegistry.blocksStorage(conversation.id)) messageFtsManager.indexConversation(conversation)
    }

    /** Save generation progress without rewriting or reindexing unchanged history. */
    suspend fun checkpointConversation(conversation: Conversation, previous: Conversation? = null) {
        if (temporaryChatRegistry.blocksStorage(conversation.id)) return
        val conversationId = conversation.id.toString()
        val previousNodes = previous?.takeIf { it.id == conversation.id }?.messageNodes
            ?.withIndex()?.associateBy { it.value.id }.orEmpty()
        // A question/answer or a full save may have written the unprojected live assistant
        // since the last checkpoint. Always restore its recoverable storage projection.
        val latestAssistantNodeId = conversation.messageNodes.lastOrNull {
            it.currentMessage.role == MessageRole.ASSISTANT
        }?.id
        val changedNodes = conversation.messageNodes.withIndex().filter { (index, node) ->
            val earlier = previousNodes[node.id]
            node.id == latestAssistantNodeId || earlier == null || earlier.index != index ||
                earlier.value.selectIndex != node.selectIndex || earlier.value.messages != node.messages
        }
        val currentNodeIds = conversation.messageNodes.map { it.id.toString() }.toSet()
        database.withTransaction {
            // A delayed writer must never recreate a deleted conversation or a temporary chat.
            if (temporaryChatRegistry.blocksStorage(conversation.id) ||
                !conversationDAO.existsById(conversationId)) return@withTransaction
            val deletedNodeIds = messageNodeDAO.getNodeIdsOfConversation(conversationId)
                .filterNot { it in currentNodeIds }
            if (temporaryChatRegistry.blocksStorage(conversation.id)) return@withTransaction
            conversationDAO.update(conversationToConversationEntity(conversation))
            deletedNodeIds.forEach { messageNodeDAO.deleteById(it) }
            if (changedNodes.isNotEmpty()) {
                messageNodeDAO.insertAll(changedNodes.map { (index, node) ->
                    MessageNodeEntity(
                        id = node.id.toString(),
                        conversationId = conversationId,
                        nodeIndex = index,
                        messages = JsonInstant.encodeToString(node.messages),
                        selectIndex = node.selectIndex,
                    )
                })
            }
            messageFtsManager.indexConversationNodes(conversation, changedNodes.map { it.value }, deletedNodeIds)
        }
    }

    /** Merge one completed translation into the latest stored node without rewriting other state. */
    suspend fun updateMessageTranslation(
        conversationId: Uuid,
        nodeId: Uuid,
        messageId: Uuid,
        translation: String?,
    ) {
        if (temporaryChatRegistry.blocksStorage(conversationId)) return
        database.withTransaction {
            if (temporaryChatRegistry.blocksStorage(conversationId)) return@withTransaction
            val node = messageNodeDAO.getNodeOfConversation(conversationId.toString(), nodeId.toString())
                ?: return@withTransaction
            val messages = JsonInstant.decodeFromString<List<UIMessage>>(node.messages)
            if (messages.none { it.id == messageId }) return@withTransaction
            messageNodeDAO.update(node.copy(messages = JsonInstant.encodeToString(messages.map { message ->
                if (message.id == messageId) message.copy(translation = translation) else message
            })))
        }
    }

    suspend fun deleteConversation(conversation: Conversation) {
        if (temporaryChatRegistry.blocksStorage(conversation.id)) return
        // 获取完整的 Conversation（包含 messageNodes）以正确清理文件
        val fullConversation = if (conversation.messageNodes.isEmpty()) {
            getConversationById(conversation.id) ?: conversation
        } else {
            conversation
        }
        messageFtsManager.deleteConversation(conversation.id.toString())
        database.withTransaction {
            // message_node 会通过 CASCADE 自动删除
            conversationDAO.delete(
                conversationToConversationEntity(conversation)
            )
        }
        filesManager.deleteChatFiles(fullConversation.files)
    }

    suspend fun searchMessages(
        keyword: String,
        sort: MessageSearchSort = MessageSearchSort.RELEVANCE,
        assistantId: Uuid? = null,
    ) = messageFtsManager.search(keyword, sort, assistantId?.let { listOf(it.toString()) })

    /** 只在 [assistantIds] 这些助手的对话里搜索 */
    suspend fun searchMessagesOfAssistants(keyword: String, assistantIds: Set<Uuid>) =
        messageFtsManager.search(keyword, MessageSearchSort.RELEVANCE, assistantIds.map { it.toString() })

    suspend fun rebuildAllIndexes(onProgress: (current: Int, total: Int) -> Unit = { _, _ -> }) {
        messageFtsManager.deleteAll()
        val allIds = conversationDAO.getAllIds()
        val total = allIds.size
        allIds.forEachIndexed { index, id ->
            val entity = conversationDAO.getConversationById(id) ?: return@forEachIndexed
            val nodes = loadMessageNodes(entity.id)
            val conversation = conversationEntityToConversation(entity, nodes)
            messageFtsManager.indexConversation(conversation)
            onProgress(index + 1, total)
        }
    }

    suspend fun deleteConversationOfAssistant(assistantId: Uuid) {
        conversationDAO.getConversationsOfAssistantForMaintenance(assistantId.toString()).forEach { entity ->
            deleteConversation(conversationEntityToConversation(entity, emptyList()))
        }
    }

    fun conversationToConversationEntity(conversation: Conversation): ConversationEntity {
        check(!temporaryChatRegistry.blocksStorage(conversation.id)) { "Temporary chats are never stored" }
        require(conversation.messageNodes.none { it.messages.any { message -> message.hasBase64Part() } }) {
            "图片尚未完成本地保存，无法写入对话。"
        }
        return ConversationEntity(
            id = conversation.id.toString(),
            title = conversation.title,
            nodes = "[]",  // nodes 现在存储在单独的表中
            createAt = conversation.createAt.toEpochMilli(),
            updateAt = conversation.updateAt.toEpochMilli(),
            assistantId = conversation.assistantId.toString(),
            chatSuggestions = JsonInstant.encodeToString(conversation.chatSuggestions),
            isPinned = conversation.isPinned,
            isArchived = conversation.isArchived,
            isLocked = conversation.isLocked,
            customSystemPrompt = conversation.customSystemPrompt ?: "",
            modeInjectionIds = JsonInstant.encodeToString(conversation.modeInjectionIds),
            lorebookIds = JsonInstant.encodeToString(conversation.lorebookIds),
            workspaceCwd = conversation.workspaceCwd ?: "",
            folderId = conversation.folderId?.toString() ?: "",
            config = conversation.config?.let { JsonInstant.encodeToString(it) } ?: "",
        )
    }

    fun conversationEntityToConversation(
        conversationEntity: ConversationEntity,
        messageNodes: List<MessageNode>
    ): Conversation {
        return Conversation(
            id = Uuid.parse(conversationEntity.id),
            title = conversationEntity.title,
            messageNodes = messageNodes.filter { it.messages.isNotEmpty() },
            createAt = Instant.ofEpochMilli(conversationEntity.createAt),
            updateAt = Instant.ofEpochMilli(conversationEntity.updateAt),
            assistantId = Uuid.parse(conversationEntity.assistantId),
            chatSuggestions = JsonInstant.decodeFromString(conversationEntity.chatSuggestions),
            isPinned = conversationEntity.isPinned,
            isArchived = conversationEntity.isArchived,
            isLocked = conversationEntity.isLocked,
            customSystemPrompt = conversationEntity.customSystemPrompt.ifEmpty { null },
            modeInjectionIds = JsonInstant.decodeFromString(conversationEntity.modeInjectionIds),
            lorebookIds = JsonInstant.decodeFromString(conversationEntity.lorebookIds),
            workspaceCwd = conversationEntity.workspaceCwd.ifEmpty { null },
            folderId = conversationEntity.folderId.ifEmpty { null }?.let { Uuid.parse(it) },
            config = conversationEntity.config.ifEmpty { null }?.let { JsonInstant.decodeFromString(it) },
        )
    }

